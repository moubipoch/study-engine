"""Study pack: everything about a course in one folder, ready for a plain chat with Claude.

    ETH/<Course>/Claude/
        CLAUDE.md                 how Claude should help (read automatically by Claude Code in this folder)
        INDEX.md                  what's here, week by week
        W03/  slides, exercises, code, notes (hard links) + "Lecture recording L03b.md" transcripts
        Exams/  past exams and solutions
        General/  script, material without a week

Use it either way:
- Claude Code (desktop app → Code) opened in that folder: it reads CLAUDE.md and the files itself.
- claude.ai: create a Project, paste CLAUDE.md into its instructions, drag the folder in as knowledge.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sqlite3
from pathlib import Path

from study.cite import fmt_time
from study.config import Course, Paths

MARK = "<!-- generated by study pack -->"
PARA_S = 60  # one transcript paragraph (with a timestamp) per ~minute


def _safe(name: str) -> str:
    return re.sub(r'[\\/:*?"<>|]+', "-", name).strip()[:120]


def _link(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        if dest.stat().st_size == src.stat().st_size:
            return
        dest.unlink()
    try:
        os.link(src, dest)
    except OSError:
        shutil.copy2(src, dest)


def _segments(con: sqlite3.Connection, paths: Paths, src: sqlite3.Row) -> list[list]:
    """[start, end, text] for a recording: the cached Whisper output, else the (de-overlapped) chunks."""
    cache = paths.cache / "transcripts" / f"{src['sha256']}.json"
    if cache.exists():
        return json.loads(cache.read_text())["segments"]
    segs, last_end = [], -1.0
    for ch in con.execute("SELECT loc_start, loc_end, text FROM chunks WHERE source_id=? ORDER BY ord", (src["id"],)):
        if ch["loc_start"] >= last_end - 0.5:
            segs.append([ch["loc_start"], ch["loc_end"], ch["text"]])
            last_end = ch["loc_end"]
    return segs


def transcript_md(course: Course, src: sqlite3.Row, segs: list[list]) -> str:
    week = f"week {src['lecture']}" if src["lecture"] is not None else "no week"
    lines = [f"# {course.name}: lecture recording {src['key']} ({week})", "",
             f"Transcript (automatic, may contain small errors). Duration {fmt_time(src['extent'])}. "
             f"Timestamps are [hh:mm:ss] into the recording.", ""]
    para, start = [], None
    for s, _, text in segs:
        if start is None:
            start = s
        para.append(text.strip())
        if s - start >= PARA_S:
            lines += [f"[{fmt_time(start)}] " + " ".join(para), ""]
            para, start = [], None
    if para:
        lines += [f"[{fmt_time(start)}] " + " ".join(para), ""]
    return "\n".join(lines)


