def _fill(template: str, **kw) -> str:
    for k, v in kw.items():
        if isinstance(v, str):
            template = template.replace(f"«{k}»", v)
    return template


def write_study_files(course: Course, out: Path, fmt: dict) -> None:
    """Slash commands and permissions for the course folder (the memory itself lives in the vault)."""
    cmds = out / ".claude" / "commands"
    cmds.mkdir(parents=True, exist_ok=True)
    for name, tpl in (("wrap", WRAP_CMD), ("check", CHECK_CMD), ("exam-model", EXAM_MODEL_CMD),
                      ("readiness", READINESS_CMD), ("gaps", GAPS_CMD), ("baseline", BASELINE_CMD)):
        (cmds / f"{name}.md").write_text(_fill(tpl, **fmt))
    settings = out / ".claude" / "settings.json"
    old = json.loads(settings.read_text()) if settings.exists() else {}
    ours = old.get("generated_by") == "study pack" or "Edit(progress/**)" in old.get("permissions", {}).get("allow", [])
    if not settings.exists() or ours:  # a settings file you wrote yourself is left alone
        reads = [f"{p}{t}" for p in fmt["planner_tools"] for t in ("get_courses", "get_day", "get_calendar")]
        vault = fmt["vault"]
        settings.write_text(json.dumps({"generated_by": "study pack", "permissions": {
            "additionalDirectories": [vault],
            "allow": ["Read", "Glob", "Grep", f"Edit(/{vault}/**)", f"Bash(git -C {vault}:*)",
                      f"Bash({fmt['readiness']}:*)", *reads]}}, indent=2) + "\n")
    old_progress = out / "progress"  # the old per-folder memory: removed when it was never used
    if old_progress.exists() and not any((old_progress / "sessions").glob("*")):
        import shutil
        shutil.rmtree(old_progress)


def build(con: sqlite3.Connection, paths: Paths, course: Course, out: Path | None = None) -> dict:
    out = out or paths.folders_root / course.folder / "Claude"
    out.mkdir(parents=True, exist_ok=True)
    stats = {"files": 0, "transcripts": 0, "dir": str(out)}
    index: dict[str, list[str]] = {}
    for src in con.execute("SELECT * FROM sources WHERE course=? ORDER BY lecture, key", (course.slug,)):
        wk = src["lecture"]
        sub = "Exams" if src["type"] == "exam" else (f"W{wk:02d}" if wk is not None else "General")
        if src["type"] in ("recording", "youtube"):
            segs = _segments(con, paths, src)
            if not segs:
                continue
            name = f"Lecture recording {src['key'].removesuffix('-rec')}.md"
            p = out / sub / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(transcript_md(course, src, segs))
            stats["transcripts"] += 1
            index.setdefault(sub, []).append(f"{name}: transcript, {fmt_time(src['extent'])}")
            continue
        f = Path(src["stored_path"] or src["path"])
        if not f.is_file():
            continue
        key = src["key"]
        name = _safe(key.replace("/", " - ")) + ("" if key.endswith(f.suffix) else f.suffix)
        _link(f, out / sub / name)
        stats["files"] += 1
        index.setdefault(sub, []).append(f"{name}: {src['type']}")
        meta = json.loads(src["meta"] or "{}")
        if meta.get("transcribed_text") or (src["type"] == "note" and f.suffix.lower() in (".png", ".jpg", ".jpeg")):
            text = " ".join(r[0] for r in con.execute("SELECT text FROM chunks WHERE source_id=? ORDER BY ord", (src["id"],)))
            if text.strip():
                (out / sub / f"{name}.txt").write_text(text)
    from study.brief import brief_path
    for (n,) in con.execute("SELECT DISTINCT lecture FROM sources WHERE course=? AND lecture IS NOT NULL", (course.slug,)):
        bp = brief_path(course, n)
        if bp.exists():
            sub = f"W{n:02d}"
            (out / sub).mkdir(parents=True, exist_ok=True)
            (out / sub / "Overview.md").write_text(bp.read_text())
            index.setdefault(sub, []).append("Overview.md: short overview of the lecture (start here)")
    lines = [f"# {course.name}: material index", ""]
    for sub in sorted(index, key=lambda s: (s == "General", s == "Exams", s)):
        lines += [f"## {sub}", *[f"- {x}" for x in sorted(index[sub])], ""]
    (out / "INDEX.md").write_text("\n".join(lines))
    style = course.style or {}
    style_txt = ""
    if style:
        style_txt = "\nCourse specifics:\n" + "\n".join(f"- {k}: {v}" for k, v in style.items() if isinstance(v, (str, list)))
    import yaml as _yaml
    planner = paths.courses / "planner.yaml"
    raw = (_yaml.safe_load(planner.read_text()) or {}) if planner.exists() else {}
    semester_start = str(raw.get("semester_start") or "?")
    vault = paths.vault
    info = course.raw.get("exam_info") or {}
    exam = course.raw.get("exam_format") or "see the course catalogue"
    exam = (f"{exam}. Date: {course.exam_date or 'not set yet (official exam plan)'}. Grading: {info.get('grading', '?')}. "
            f"ECTS {info.get('ects', '?')}.") if not course.project_only else "no exam: project-graded."
    fmt = {"mark": MARK, "name": course.name, "slug": course.slug, "short": course.short,
           "vault": str(vault), "planner_name": course.planner_name,
           "student": paths.settings.get("student") or "a university student",
           "planner_tools": list(paths.settings.get("planner_tools") or []),
           "readiness": f"uv run --project {paths.root} study readiness {course.slug}", "semester_start": semester_start,
           "target": info.get("target", "maximum"), "exam": exam, "style": style_txt}
    ins = out / "CLAUDE.md"
    if not ins.exists() or MARK in ins.read_text():  # never overwrite instructions the user rewrote
        ins.write_text(_fill(INSTRUCTIONS, **fmt))
    write_study_files(course, out, fmt)
    return stats
